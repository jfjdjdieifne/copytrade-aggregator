#!/bin/bash
# ═══════════════════════════════════════════════════════════════════════════
#  تشغيل تلقائي — الصق هذا كله في "User data" عند إنشاء السيرفر
# ═══════════════════════════════════════════════════════════════════════════
#
#  لا SSH. لا مفاتيح. لا محرر نصوص. لا أوامر.
#
#  غيّر السطرين تحت فقط، والصق الكل في حقل User data، وشغّل السيرفر.
#  بعد دقيقتين رح توصلك رسالة على التلغرام: "🚀 الرادار اشتغل"
#
#  إذا وصلتك الرسالة → كل شي تمام. ما تحتاج تسوي شي تاني.
#  إذا ما وصلت → السجل موجود على السيرفر في /var/log/radar-setup.log
#
# ═══════════════════════════════════════════════════════════════════════════

# ┌────────────────────────────────────────────────────────────────────────┐
# │  غيّر هذين السطرين فقط  —  الباقي لا تلمسه                              │
# └────────────────────────────────────────────────────────────────────────┘

TOKEN="ضع_التوكن_هنا"
CHAT_ID="ضع_رقم_المحادثة_هنا"

# ┌────────────────────────────────────────────────────────────────────────┐
# │  من هنا ما تحتاج تغيّر شي                                                │
# └────────────────────────────────────────────────────────────────────────┘

set -uo pipefail
export DEBIAN_FRONTEND=noninteractive
exec > /var/log/radar-setup.log 2>&1

BRANCH="arena/4bff239f-copytrade-aggregator"
REPO="https://github.com/jfjdjdieifne/copytrade-aggregator.git"
DIR=/home/ubuntu/radar

log() { echo "[$(date +%H:%M:%S)] $*"; }

log "بدأ التثبيت"

# ── ٠. تحقّق من المفاتيح أولاً، قبل أي انتظار ──────────────────────────────
# لو حطينا هذا بعد الانتظار، المستخدم اللي نسي يبدّل القيم يستنى خمس دقايق
# وبعدين يشوف سيرفر شغال ما يبعث ولا رسالة — وأسوأ من الفشل إنو يبدو ناجحاً.
if [[ "$TOKEN" == "ضع_التوكن_هنا" || -z "$TOKEN" ]]; then
  log "✗ خطأ: ما غيّرت TOKEN — بدّل السطر وحط التوكن من @BotFather"
  exit 1
fi
if [[ "$CHAT_ID" == "ضع_رقم_المحادثة_هنا" || -z "$CHAT_ID" ]]; then
  log "✗ خطأ: ما غيّرت CHAT_ID — بدّل السطر وحط رقم محادثتك"
  exit 1
fi

# ── ١. انتظر الشبكة ────────────────────────────────────────────────────────
# الـ user data يبدأ أحياناً قبل ما تكون الشبكة جاهزة. بدون هذا الانتظار
# الـ clone يفشل والسكربت يموت بهدوء.
log "انتظار الشبكة…"
for i in $(seq 1 60); do
  if curl -s -o /dev/null --max-time 5 https://github.com; then
    log "الشبكة جاهزة"
    break
  fi
  sleep 5
done

# ── ٢. انتظر قفل apt ───────────────────────────────────────────────────────
# أوبونتو يشغّل تحديثات تلقائية عند أول إقلاع. لو حاولنا نثبّت بنفس اللحظة
# بنفشل بصمت. ننتظر لين يتحرّر القفل.
log "انتظار قفل apt…"
for i in $(seq 1 60); do
  if ! fuser /var/lib/dpkg/lock-frontend >/dev/null 2>&1; then
    break
  fi
  sleep 5
done

apt-get update -y  || log "تحذير: apt-get update"
apt-get install -y git curl || log "تحذير: تثبيت git"

# ── ٤. نزّل المشروع ────────────────────────────────────────────────────────
# المنصات تسمّي مستخدمها بأسماء مختلفة: أوبونتو Ubuntu يسمّيه ubuntu،
# Debian يستعمل admin، CentOS يستعمل ec2-user. assumption ثابت لـ ubuntu
# هو بالظبط نوع الفشل اللي يخلّي الخدمة تموت بـ status=217/USER
# ونلاقي install.sh بيقول "✔ installed" فوق جثة خدمة ميتة.
if id ubuntu >/dev/null 2>&1; then
  SVC_USER=ubuntu
else
  SVC_USER="$(id -un)"
fi
log "مستخدم الخدمة: $SVC_USER"

rm -rf "$DIR"
log "تنزيل المشروع…"
for attempt in 1 2 3; do
  if git clone --branch "$BRANCH" --single-branch "$REPO" "$DIR" \
     ; then
    log "تم التنزيل"
    break
  fi
  log "محاولة $attempt فشلت، نعيد…"
  sleep 10
done

if [[ ! -f "$DIR/entry.py" ]]; then
  log "✗ خطأ: التنزيل فشل"
  exit 1
fi

# ── ٥. اكتب الإعداد ────────────────────────────────────────────────────────
printf 'TELEGRAM_BOT_TOKEN=%s\nTELEGRAM_CHAT_ID=%s\n' "$TOKEN" "$CHAT_ID" > "$DIR/.env"
chmod 600 "$DIR/.env"
chown -R "$SVC_USER":"$SVC_USER" "$DIR" || log "تحذير: chown"
log "الإعداد مكتوب"

# ── ٦. ثبّت الخدمة ─────────────────────────────────────────────────────────
cd "$DIR"
SERVICE_USER="$SVC_USER" REPO_DIR="$DIR" ./deploy/aws/install.sh \
 
log "install.sh انتهى"

# ── ٧. تحقّق أن الخدمة شغالة فعلاً ───────────────────══════────────────────
# `systemctl enable` يقدر ينجح والعملية تموت بعد ثانية. الفحص الحقيقي هو
# إنو الخدمة active _و_ عدّت دورات — مو إنو الملف انكتب.
sleep 20
if systemctl is-active --quiet copytrade; then
  log "✔ الخدمة شغالة"
else
  log "✗ الخدمة مو شغالة — آخر ٢٠ سطر:"
  journalctl -u copytrade --no-pager -n 20
fi

log "انتهى"
